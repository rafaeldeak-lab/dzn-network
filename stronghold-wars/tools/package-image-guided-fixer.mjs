import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'preview/assets/models/squads-v8');
mkdirSync(output, { recursive: true });
const jobs = [
  '9d5ba989-d418-4a72-a065-0ccbcde4418d',
  '2549a86c-c1ce-4e5b-bd3f-291a3bdf0b1e',
  '3f5e7c65-27c2-400c-bb3e-dff2fb4a1525',
  '7bff115e-d387-4c43-b766-e090046d7534',
  '2744402d-ff10-4e52-9d3d-0c5132984d1e',
];
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const assets = {};
for (let level = 1; level <= 5; level++) {
  const name = `engineer_l0${level}`;
  const file = `assets/models/squads-v8/${name}.glb`;
  const source = `source-art/rosebud-models/${name}.glb`;
  const reference = `assets/portraits/squads-final/${name}.png`;
  const sourceBytes = readFileSync(join(root, source));
  const referenceBytes = readFileSync(join(root, 'preview', reference));
  const riggedPath = join(root, `review/fixer-l0${level}-rig.glb`);
  copyFileSync(riggedPath, join(root, 'preview', file));
  const bytes = readFileSync(join(root, 'preview', file));
  if (bytes.toString('ascii', 0, 4) !== 'glTF' || bytes.readUInt32LE(8) !== bytes.length) throw new Error(`Invalid ${name} GLB`);
  const gltf = JSON.parse(bytes.toString('utf8', 20, 20 + bytes.readUInt32LE(12)));
  const triangles = gltf.meshes.flatMap(mesh => mesh.primitives).reduce((count, primitive) => count + gltf.accessors[primitive.indices].count / 3, 0);
  if (!gltf.skins?.length || !gltf.animations?.some(clip => clip.name === 'DZN_Operative_Walk') || !gltf.animations?.some(clip => clip.name === 'DZN_Operative_Idle') || gltf.images?.length < 2) throw new Error(`Incomplete ${name} rig`);
  assets[name] = {
    file, source, reference, rosebudJob: jobs[level - 1], bytes: bytes.length, sha256: sha(bytes),
    sourceSha256: sha(sourceBytes), referenceSha256: sha(referenceBytes), triangles,
    skins: gltf.skins.length, textures: gltf.images.length,
    animations: ['DZN_Operative_Walk', 'DZN_Operative_Idle'], heightMetres: 1.8,
  };
}
writeFileSync(join(output, 'manifest.json'), `${JSON.stringify({
  schemaVersion: 1,
  provenance: 'Five stages generated by Rosebud Rosie image-to-3D from the existing DZN Fixer portraits using 5,000 owner-account credits. Static sources retained; rigs and walk/idle clips added locally in Blender. Level 3 display-floor geometry removed before rigging.',
  usage: 'DZN Stronghold Wars local preview. Rights remain subject to the owner account and Rosebud terms.',
  coordinateSystem: 'glTF Y-up; Fixer faces +Z in the game', assets,
}, null, 2)}\n`);
console.log('Packaged five image-guided Fixer levels:', Object.values(assets).map(asset => asset.bytes));
